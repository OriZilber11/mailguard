"""Refresh app/data/bad_domains.txt from the OpenPhish public feed. Run: python3 scripts/update_feeds.py"""
import re
import sys
from pathlib import Path
from urllib.request import Request, urlopen
from urllib.parse import urlsplit

FEED = "https://openphish.com/feed.txt"
OUT = Path(__file__).parent.parent / "app" / "data" / "bad_domains.txt"
# Many users share ONE hostname (content differs by path): never block these.
SHARED = ("google.com", "googleusercontent.com", "githubusercontent.com", "sharepoint.com", "dropbox.com",
          "onedrive.live.com", "forms.gle", "microsoft.com", "office.com", "canva.com", "typeform.com",
          "notion.site", "wordpress.com", "godaddysites.com")
# Each user gets their own subdomain: blocking one exact tenant host is safe, the bare platform is not.
TENANT = ("pages.dev", "blogspot.com", "github.io", "workers.dev", "vercel.app", "netlify.app", "weebly.com",
          "webflow.io", "web.app", "firebaseapp.com", "herokuapp.com", "wixsite.com")
HOST = re.compile(r"^(?:[a-z0-9-]+\.)+[a-z]{2,}$")
SEED = ["evil.test", "phish.test", "malware-download.test"]  # demo entries, always kept

raw = urlopen(Request(FEED, headers={"User-Agent": "mailguard-feed-updater"}), timeout=30).read(5_000_000)
hosts = {(urlsplit(u.strip()).hostname or "").lower() for u in raw.decode("utf-8", "ignore").splitlines()}
ok = {h for h in hosts if HOST.match(h) and not any(h == s or h.endswith("." + s) for s in SHARED) and h not in TENANT}
OUT.write_text("# One host per line (hosts and their subdomains match). Generated by scripts/update_feeds.py\n"
               + "\n".join(SEED + sorted(ok)) + "\n")
print(f"{len(ok)} hosts written, {len(hosts) - len(ok)} skipped (IPs, shared platforms, invalid)", file=sys.stderr)
